import fs from 'node:fs'
import path from 'node:path'
import { collectLegacyPaths, legacyPathsPath, readCommittedLegacyPaths, sortLegacyPaths } from './legacy-paths.mjs'

const generated = sortLegacyPaths(collectLegacyPaths())
const committed = sortLegacyPaths(readCommittedLegacyPaths())
const nextJson = `${JSON.stringify(generated, null, 2)}\n`
const redirectsPath = path.resolve(legacyPathsPath, '..', '..', '..', 'public', '_redirects')
const workerRedirectsPath = path.resolve(
  legacyPathsPath,
  '..',
  '..',
  '..',
  'src',
  'generated',
  'legacy-redirects.ts',
)

function buildRedirectsFile(paths) {
  const lines = [
    '# Generated by scripts/sync-legacy-paths.mjs',
    ...Object.entries(paths).map(([from, to]) => `${from} ${to} 301`),
    '/*/ /:splat 301',
    '',
  ]
  return lines.join('\n')
}

function buildWorkerRedirectsFile(paths) {
  const lines = [
    '// Generated by scripts/sync-legacy-paths.mjs',
    '// Keep apps/marketing/public/_redirects as the legacy redirect source.',
    `export const legacyRedirects = ${JSON.stringify(paths, null, 2)} as const`,
    '',
  ]
  return lines.join('\n')
}

const nextRedirects = buildRedirectsFile(generated)
const nextWorkerRedirects = buildWorkerRedirectsFile(generated)

if (process.argv.includes('--check')) {
  if (JSON.stringify(generated) !== JSON.stringify(committed)) {
    console.error('Legacy path mappings are out of sync with content metadata.')
    process.exit(1)
  }
  if (!fs.existsSync(redirectsPath) || fs.readFileSync(redirectsPath, 'utf8') !== nextRedirects) {
    console.error('_redirects file is out of sync with legacy path mappings.')
    process.exit(1)
  }
  if (
    !fs.existsSync(workerRedirectsPath) ||
    fs.readFileSync(workerRedirectsPath, 'utf8') !== nextWorkerRedirects
  ) {
    console.error('Worker legacy redirect map is out of sync with legacy path mappings.')
    process.exit(1)
  }
  if (
    !fs.existsSync(workerRedirectsPath) ||
    fs.readFileSync(workerRedirectsPath, 'utf8') !== nextWorkerRedirects
  ) {
    console.error('Worker legacy redirect map is out of sync with legacy path mappings.')
    process.exit(1)
  }
  console.log(`Legacy path mappings are in sync (${Object.keys(generated).length} redirects).`)
  process.exit(0)
}

fs.writeFileSync(legacyPathsPath, nextJson)
fs.writeFileSync(redirectsPath, nextRedirects)
fs.mkdirSync(path.dirname(workerRedirectsPath), { recursive: true })
fs.writeFileSync(workerRedirectsPath, nextWorkerRedirects)
console.log(
  `Updated legacy path mappings, _redirects, and Worker redirect map (${Object.keys(generated).length} redirects).`,
)
